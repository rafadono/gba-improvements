#!/usr/bin/env python3
"""Generate a C++ source embedding TrueType fonts as byte arrays, with indexed accessors.

Usage:
  gen_font_data.py [options] font1.ttf font2.ttf ... > fonts_data.cpp

Output (stdout): one `static const unsigned char kData<name>[N]` per font, then
  const unsigned char* <data-fn>(int index);   // nullptr when out of range
  size_t <size-fn>(int index);                 // 0 when out of range
  int <count-fn>();                            // only when --count-fn is given
inside `namespace <namespace>`. The index follows the command-line order, so register the fonts
in the same order (for example with gbaimp::text::FontLibrary::add_builtin_font).

Options:
  --namespace NS      C++ namespace, may be nested as a::b (default: embedded_fonts)
  --include HEADER    header included by the generated file after <cstddef> (default: none)
  --data-fn NAME      default: face_data
  --size-fn NAME      default: face_size
  --count-fn NAME     also emit `int NAME()` returning the number of fonts
  --banner TEXT       text of the leading comment (default: a GENERATED notice)

Fonts are usually subset first with fontTools, for example:
  python -m fontTools.subset F.ttf --unicodes='U+0020-007E,U+00A0-00FF,U+2018,U+2019,U+201C,U+201D,U+2026,U+2013,U+2014' --no-hinting --desubroutinize --layout-features='' --name-IDs='0,1,2,3,13,14' --output-file=F.sub.ttf
"""
import argparse
import os
import sys


def c_identifier(path):
    return "kData" + "".join(ch for ch in os.path.basename(path).split(".")[0] if ch.isalnum())


def generate(fonts, namespace="embedded_fonts", include=None, data_fn="face_data", size_fn="face_size",
             count_fn=None, banner=None):
    """`fonts` is a list of (path, bytes); returns the source text."""
    out = ["// " + (banner or "GENERATED by gen_font_data.py - do not edit."),
           "#include <cstddef>"]
    if include:
        out.append('#include "%s"' % include)
    out.append("")
    out.append("namespace " + " { namespace ".join(namespace.split("::")) + " {")
    out.append("")
    names = []
    seen = set()
    for path, data in fonts:
        ident = c_identifier(path)
        if ident in seen:
            raise ValueError("two fonts map to the same identifier %s (rename one of the files)" % ident)
        seen.add(ident)
        names.append((ident, len(data)))
        out.append("static const unsigned char %s[%d] = {" % (ident, len(data)))
        for i in range(0, len(data), 24):
            out.append("    " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append("")
    out.append("const unsigned char* %s(int face) {" % data_fn)
    out.append("    switch (face) {")
    for i, (ident, _) in enumerate(names):
        out.append("        case %d: return %s;" % (i, ident))
    out.append("        default: return nullptr;")
    out.append("    }")
    out.append("}")
    out.append("size_t %s(int face) {" % size_fn)
    out.append("    switch (face) {")
    for i, (_, n) in enumerate(names):
        out.append("        case %d: return %d;" % (i, n))
    out.append("        default: return 0;")
    out.append("    }")
    out.append("}")
    out.append("")
    if count_fn:
        out.append("int %s() { return %d; }" % (count_fn, len(names)))
        out.append("")
    out.append("}" * (namespace.count("::") + 1) + " // namespace " + namespace)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("fonts", nargs="+")
    ap.add_argument("--namespace", default="embedded_fonts")
    ap.add_argument("--include")
    ap.add_argument("--data-fn", default="face_data")
    ap.add_argument("--size-fn", default="face_size")
    ap.add_argument("--count-fn")
    ap.add_argument("--banner")
    args = ap.parse_args(argv)
    fonts = []
    for path in args.fonts:
        with open(path, "rb") as f:
            fonts.append((path, f.read()))
    sys.stdout.write(generate(fonts, args.namespace, args.include, args.data_fn, args.size_fn,
                              args.count_fn, args.banner))
    return 0


if __name__ == "__main__":
    sys.exit(main())
