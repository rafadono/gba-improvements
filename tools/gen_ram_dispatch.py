"""Generate a native RAM-overlay dispatcher (C++ header + source).

Scans cached recompiler output (``.c`` files) for functions located in
IWRAM/EWRAM, extracts them, and emits ``ram_overlay_dispatch.h/.cpp``. The
.cpp holds the translated routines, the sorted table and a single
``GBAIMP_DEFINE_RAM_DISPATCH_N`` line: the search, the hook and the install
function come from the library (``gbaimp/ram_dispatch_gbarecomp.h``). All
generated identifiers are built from ``--symbol-prefix``.

``--migrate FILE...`` rewrites a .cpp generated by an older version of this
script (self-contained hook code at the end of the file) to the library-based
form without needing the recompiler cache.
"""

import argparse
import glob
import os
import re


def is_ram_pc(pc):
    return (0x02000000 <= pc < 0x02040000) or (0x03000000 <= pc < 0x03008000)


def c_string_escape(text):
    """Escape for a plain C string literal (no printf format involved)."""
    return text.replace("\\", "\\\\").replace('"', '\\"')


def render_header(prefix):
    return (
        "#pragma once\n"
        "#include <cstdint>\n"
        "\n"
        f'extern "C" int {prefix}_ram_dispatch_hook(uint32_t pc, int thumb);\n'
        f"void {prefix}_install_ram_dispatch();\n"
    )


def render_cpp(entries, prefix, game_name, runtime_header):
    """Full text of ram_overlay_dispatch.cpp for entries sorted by (pc, thumb)."""
    log_name = c_string_escape(game_name)
    out = [
        f"// AUTO-GENERATED RAM overlay native dispatcher for {game_name}\n",
        f"// Directly compiles and dispatches all {len(entries)} IWRAM/EWRAM routines natively.\n",
        "\n",
        '#include "ram_overlay_dispatch.h"\n',
        f'#include "{runtime_header}"\n',
        '#include "gbaimp/ram_dispatch_gbarecomp.h"\n',
        "#include <algorithm>\n",
        "#include <cstdio>\n",
        "\n",
        "namespace {\n",
        "\n",
    ]
    for e in entries:
        out.append(f"// --- Function 0x{e['pc']:08X} ({'thumb' if e['thumb'] else 'arm'}) ---\n")
        out.append(e["code"])
        out.append("\n\n")
    out.append("// Sorted by (pc, thumb); searched by gbaimp::find_ram_dispatch.\n")
    out.append("static const gbaimp::RamDispatchEntry kRamDispatchEntries[] = {\n")
    for e in entries:
        out.append(f"    {{ 0x{e['pc']:08X}u, {e['thumb']}, {e['fn_name']} }},\n")
    if not entries:
        out.append("    { 0u, 0, nullptr },  // placeholder: C++ has no empty arrays; the count below is 0\n")
    out.append("};\n\n")
    out.append("} // namespace\n\n")
    out.append(f'GBAIMP_DEFINE_RAM_DISPATCH_N({prefix}, "{log_name}", kRamDispatchEntries, {len(entries)})\n')
    return "".join(out)


_TAIL_RE = re.compile(r'extern "C" int (?P<p>[A-Za-z_][A-Za-z0-9_]*)_ram_dispatch_hook\(uint32_t pc, int thumb\) \{')
_LOG_RE = re.compile(r'std::printf\("\[(?P<name>(?:[^"\\]|\\.)*)\] Native RAM overlay dispatcher installed')


def migrate_text(text):
    """Convert an old self-contained generated .cpp to the library-based form.

    Returns the new text, or None when the text is already migrated or is not a generated
    dispatcher. Line endings (LF / CRLF) are preserved. Raises ValueError on a recognised
    but unexpected layout.
    """
    if "GBAIMP_DEFINE_RAM_DISPATCH" in text:
        return None
    crlf = "\r\n" in text
    work = text.replace("\r\n", "\n") if crlf else text
    m = _TAIL_RE.search(work)
    if not m:
        return None
    prefix = m.group("p")
    tail = work[m.start():]
    if f"g_runtime_ram_dispatch_hook = {prefix}_ram_dispatch_hook;" not in tail:
        raise ValueError("unexpected tail: hook installation not found")
    lm = _LOG_RE.search(tail)
    if not lm:
        raise ValueError("unexpected tail: install log line not found")
    log_name = lm.group("name").replace("%%", "%")   # was a printf format; now a plain %s argument
    head = work[:m.start()]
    if "kRamDispatchCount" not in head:
        raise ValueError("kRamDispatchCount not found before the hook")
    inc = re.search(r'^#include "[^"\n]*runtime_arm\.h"\n', head, re.M)
    if not inc:
        raise ValueError("runtime header include not found")
    head = head[:inc.end()] + '#include "gbaimp/ram_dispatch_gbarecomp.h"\n' + head[inc.end():]
    new = head + f'GBAIMP_DEFINE_RAM_DISPATCH_N({prefix}, "{log_name}", kRamDispatchEntries, kRamDispatchCount)\n'
    return new.replace("\n", "\r\n") if crlf else new


def migrate_files(paths):
    for path in paths:
        with open(path, "r", encoding="utf-8", errors="surrogateescape", newline="") as f:
            text = f.read()
        new = migrate_text(text)
        if new is None:
            print(f"{path}: nothing to migrate")
            continue
        with open(path, "w", encoding="utf-8", errors="surrogateescape", newline="") as f:
            f.write(new)
        print(f"{path}: migrated")


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate a native RAM-overlay dispatcher (C++) from cached "
                    "recompiler .c output of IWRAM/EWRAM functions.")
    parser.add_argument("--root", default=".",
                        help="project root used to resolve default paths (default: current directory)")
    parser.add_argument("--cache-dir", default=None,
                        help="recompiler cache directory (default: <root>/recomp_cache)")
    parser.add_argument("--cache-pattern", default=os.path.join("**", "abi5-ram3", "*.c"),
                        help="glob, relative to the cache dir, selecting RAM-function .c files "
                             "(default: **/abi5-ram3/*.c)")
    parser.add_argument("--out-dir", default=None,
                        help="output directory for ram_overlay_dispatch.h/.cpp (default: <root>/src)")
    parser.add_argument("--symbol-prefix", default="recomp",
                        help="prefix for generated C identifiers: <prefix>_ram_dispatch_hook and "
                             "<prefix>_install_ram_dispatch (default: recomp)")
    parser.add_argument("--game-name", default="GBA game",
                        help="game name used in the generated header comment and log string "
                             "(default: 'GBA game')")
    parser.add_argument("--runtime-header", default="runtime_arm.h",
                        help="runtime header declaring g_runtime_ram_dispatch_hook (default: runtime_arm.h)")
    parser.add_argument("--migrate", nargs="+", metavar="FILE", default=None,
                        help="rewrite old-style generated .cpp files in place to the library-based form and exit")
    args = parser.parse_args(argv)

    if args.migrate:
        migrate_files(args.migrate)
        return

    prefix = args.symbol_prefix
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", prefix):
        parser.error("--symbol-prefix must be a valid C identifier")
    game_name = " ".join(args.game_name.split())
    root = args.root
    cache_dir = args.cache_dir or os.path.join(root, "recomp_cache")
    out_dir = args.out_dir or os.path.join(root, "src")
    cache_glob = os.path.join(cache_dir, args.cache_pattern)
    c_files = glob.glob(cache_glob, recursive=True)

    print(f"Scanning {len(c_files)} total .c files in cache...")

    entries = []
    seen_keys = set()

    for path in c_files:
        filename = os.path.basename(path)
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()

        m = re.search(r"// function 0x([0-9A-Fa-f]+) mode=(arm|thumb) end=0x([0-9A-Fa-f]+)", content)
        if not m:
            continue

        pc_str, mode_str, end_str = m.groups()
        pc = int(pc_str, 16)

        # Only process RAM (IWRAM and EWRAM) routines
        if not is_ram_pc(pc):
            continue

        thumb = 1 if mode_str == "thumb" else 0
        key = (pc, thumb)
        if key in seen_keys:
            continue
        seen_keys.add(key)

        end_pc = int(end_str, 16)

        fn_start = content.find(f"func_{pc_str}")
        if fn_start == -1:
            fn_start = content.find(f"func_{pc:08X}")
        if fn_start == -1:
            print(f"Warning: could not find func_{pc:08X} in {filename}")
            continue

        decl_start = content.rfind("OVL_EXPORT void", 0, fn_start)
        if decl_start == -1:
            decl_start = content.rfind("void", 0, fn_start)

        fn_code = content[decl_start:]
        # Normalize OVL_EXPORT void func_XXXXX to static void ram_func_XXXXX
        fn_code = re.sub(r"OVL_EXPORT\s+void\s+func_([0-9A-Fa-f]+)", r"static void ram_func_\1", fn_code, count=1)

        entries.append({
            "pc": pc,
            "thumb": thumb,
            "end": end_pc,
            "fn_name": f"ram_func_{pc:08X}",
            "code": fn_code.strip()
        })

    # Sort entries by PC then thumb mode for binary search
    entries.sort(key=lambda x: (x["pc"], x["thumb"]))
    # The same address can hold an ARM and a Thumb routine (different code copied there at different
    # times). Both would be named ram_func_<PC>: give the later (Thumb) one a suffix so the file compiles.
    for prev, cur in zip(entries, entries[1:]):
        if prev["pc"] == cur["pc"]:
            cur["fn_name"] = f"ram_func_{cur['pc']:08X}_thumb"
            cur["code"] = re.sub(r"static void ram_func_[0-9A-Fa-f]+", "static void " + cur["fn_name"], cur["code"], count=1)
    print(f"Extracted {len(entries)} unique RAM routines (IWRAM/EWRAM).")

    os.makedirs(out_dir, exist_ok=True)
    out_header_path = os.path.join(out_dir, "ram_overlay_dispatch.h")
    with open(out_header_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_header(prefix))
    print(f"Wrote {out_header_path}")

    out_cpp_path = os.path.join(out_dir, "ram_overlay_dispatch.cpp")
    with open(out_cpp_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_cpp(entries, prefix, game_name, args.runtime_header))
    print(f"Wrote {out_cpp_path} successfully ({len(entries)} functions).")


if __name__ == "__main__":
    main()
