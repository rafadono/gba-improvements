#!/usr/bin/env python3
"""Extract function symbols from a ROM's debug registration tables.

Some games register tasks and modes in descriptor tables (there may be
several, e.g. per-area task tables), each entry carrying a pointer to a debug
name string followed by function pointers:

  task entry: {name*, fn0, fn1, fn2, fn3, work_size} (24 bytes)
  mode entry: {name*, fn0, fn1, fn2, ram*}           (20 bytes)

Rather than hardcoding table addresses, scan the whole ROM for aligned words
that point at a <task-prefix>*/<mode-prefix>* string (default "task_" and
"mode_") and validate the words that follow.
Callback semantics are unconfirmed, so functions are named <name>_<index>.
Emits a luvdis config: "thumb_func <addr> <name>" per function.
"""

import argparse
import re
import struct
import sys


def hex_int(text):
    """argparse type: integer accepting 0x... hex or decimal."""
    return int(text, 0)


def main():
    parser = argparse.ArgumentParser(
        description="Extract function symbols from task/mode descriptor tables "
                    "found by scanning a GBA ROM for pointers to debug name strings.")
    parser.add_argument("rom", help="path to the .gba ROM image")
    parser.add_argument("-o", "--output", default="/dev/stdout",
                        help="output file (default: stdout)")
    parser.add_argument("--rom-base", type=hex_int, default=0x08000000,
                        help="ROM load address (default: 0x08000000)")
    parser.add_argument("--code-size", type=hex_int, default=0x122000,
                        help="size in bytes of the code region starting at --rom-base; "
                             "function pointers must fall inside it (default: 0x122000)")
    parser.add_argument("--task-prefix", default="task_",
                        help="name prefix of task descriptors, 4 function pointers each (default: task_)")
    parser.add_argument("--mode-prefix", default="mode_",
                        help="name prefix of mode descriptors, 3 function pointers each (default: mode_)")
    args = parser.parse_args()

    rom_base = args.rom_base
    code_end = rom_base + args.code_size
    task_prefix = args.task_prefix.encode()
    mode_prefix = args.mode_prefix.encode()

    with open(args.rom, "rb") as rf:
        data = rf.read()

    names = {}
    pattern = (rb"(?<=\x00)((?:" + re.escape(task_prefix) + rb"|" + re.escape(mode_prefix)
               + rb")[A-Za-z0-9_]+)\x00")
    for m in re.finditer(pattern, data):
        nfuncs = 4 if m.group(1).startswith(task_prefix) else 3
        names[rom_base + m.start(1)] = (m.group(1).decode(), nfuncs)

    def valid_fn(w):
        return w == 0 or (w & 1 and rom_base < w < code_end)

    syms = {}
    words = struct.unpack(f"<{len(data)//4}I", data[: len(data) // 4 * 4])
    for i, w in enumerate(words):
        if w not in names:
            continue
        name, nfuncs = names[w]
        fns = words[i + 1 : i + 1 + nfuncs]
        if len(fns) == nfuncs and all(map(valid_fn, fns)) and any(fns):
            for k, fn in enumerate(fns):
                if fn:
                    syms.setdefault(fn & ~1, f"{name}_{k}")

    with open(args.output, "w") as f:
        f.write("# generated by tools/gen_symbols.py -- do not edit\n")
        for addr in sorted(syms):
            f.write(f"thumb_func 0x{addr:08X} {syms[addr]}\n")
    print(f"{len(syms)} named functions", file=sys.stderr)


if __name__ == "__main__":
    main()
